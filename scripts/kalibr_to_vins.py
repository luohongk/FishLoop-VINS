#!/usr/bin/env python3
"""
kalibr_to_vins.py
=================

Convert a Kalibr calibration result (camera intrinsics + extrinsics + IMU)
into a complete VINS-Fisheye configuration set:

    <out_dir>/cam0_mei.yaml
    <out_dir>/cam1_mei.yaml          (one per camera in the chain)
    <out_dir>/stereo_imu_config.yaml (main config; uses the chosen pair)
    <launch_dir>/<launch_name>.launch (optional)

Inputs expected in --kalibr-dir (Kalibr default file names):
    *camchain-imucam*.yaml   (gives T_cam_imu for the reference camera)
    *camchain*.yaml          (intrinsics + chain of T_cn_cnm1)
    *imu*.yaml               (IMU noise/random-walk + update_rate)

Camera model assumption
-----------------------
Supported Kalibr camera models are ``eucm-none``, ``omni-radtan``,
``pinhole-radtan`` and ``pinhole-equi``. They are emitted as EUCM, MEI,
PINHOLE and KANNALA_BRANDT respectively.

Usage
-----
    python3 scripts/kalibr_to_vins.py \
        --kalibr-dir my_kalibr_result \
        --out-dir   config/my_kalibr_fisheye \
        --cam-pair  0,1 \
        --topic-map 0:/fisheye/left/image_raw,1:/fisheye/right/image_raw,\\
2:/fisheye/bleft/image_raw,3:/fisheye/bright/image_raw \
        --imu-topic /imu_data_raw \
        --compressed \
        --launch    my_kalibr_fisheye

Re-run the script whenever the Kalibr result changes; it is idempotent.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from typing import Dict, Tuple

import numpy as np
import yaml


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------

def find_one(pattern: str, root: Path) -> Path:
    matches = sorted(root.glob(pattern))
    if not matches:
        raise FileNotFoundError(f"No file matching {pattern!r} under {root}")
    if len(matches) > 1:
        print(f"[warn] multiple matches for {pattern!r}: {matches}, using {matches[0]}")
    return matches[0]


def load_yaml(path: Path) -> dict:
    with path.open() as f:
        return yaml.safe_load(f)


def invert_se3(T: np.ndarray) -> np.ndarray:
    R, t = T[:3, :3], T[:3, 3]
    Ti = np.eye(4)
    Ti[:3, :3] = R.T
    Ti[:3, 3] = -R.T @ t
    return Ti


def num_cameras(camchain: dict) -> int:
    n = 0
    while f"cam{n}" in camchain:
        n += 1
    return n


def T_imu_cam(camchain: dict, T_imu_cam0: np.ndarray, n: int) -> np.ndarray:
    """body_T_camN = T_imu_cam0 * inv(T_camN_cam0).
    T_camN_cam0 = T_cn_cnm1[N] @ ... @ T_cn_cnm1[1]."""
    if n == 0:
        return T_imu_cam0
    T_camN_cam0 = np.eye(4)
    for i in range(1, n + 1):
        T_ci_cim1 = np.array(camchain[f"cam{i}"]["T_cn_cnm1"])
        T_camN_cam0 = T_ci_cim1 @ T_camN_cam0
    return T_imu_cam0 @ invert_se3(T_camN_cam0)


def fmt_matrix(M: np.ndarray, indent: str = "           ") -> str:
    rows = []
    for r in M:
        rows.append(indent + ", ".join(f"{v: .16e}" for v in r))
    return ",\n".join(rows)


