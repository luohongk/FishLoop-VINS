def emit_launch(launch_dir: Path, launch_name: str, config_path: Path,
                padder_specs: "list | None" = None,
                viz_spec: "dict | None" = None) -> Path:
    """Emit a roslaunch file. If padder_specs is non-empty, prepend
    pad_fisheye_node.py instances. Each spec is a dict with keys:
        input, output, input_compressed, pad_top, pad_bottom, pad_left, pad_right

    If viz_spec is given, also append a viz_fisheye_tracking.py node. Keys:
        left_topic, right_topic, left_compressed, right_compressed, display
    """
    rel = os.path.relpath(config_path, launch_dir.parent / "..")
    repo_root = (launch_dir.parent / "..").resolve()
    scripts_rel = "../scripts/pad_fisheye_node.py"

    def _pkg_rel(abs_path: str) -> str:
        """Convert an absolute path under repo_root to '$(find fishloop_vins)/../<rel>'.
        Leave it untouched if it's empty or lives outside the package.
        Without this, an absolute host path baked into the launch file fails
        when ROS runs inside a container that mounts the repo at a different
        absolute path."""
        if not abs_path:
            return abs_path
        try:
            p = Path(abs_path).resolve()
            rel_p = p.relative_to(repo_root)
            return f"$(find fishloop_vins)/../{rel_p}"
        except (ValueError, OSError):
            return abs_path
    padder_xml = ""
    if padder_specs:
        for i, p in enumerate(padder_specs):
            padder_xml += f"""
    <!-- Padder for cam{i}: rebuilds symmetric fisheye geometry -->
    <node pkg="fishloop_vins" type="pad_fisheye_node.py" name="fisheye_padder_{i}"
          output="screen" required="true">
        <param name="input"            type="string" value="{p['input']}"/>
        <param name="output"           type="string" value="{p['output']}"/>
        <param name="input_compressed" type="bool"   value="{str(bool(p['input_compressed'])).lower()}"/>
        <param name="pad_top"          type="int"    value="{int(p['pad_top'])}"/>
        <param name="pad_bottom"       type="int"    value="{int(p['pad_bottom'])}"/>
        <param name="pad_left"         type="int"    value="{int(p['pad_left'])}"/>
        <param name="pad_right"        type="int"    value="{int(p['pad_right'])}"/>
    </node>
"""
        padder_xml += "\n    <!-- Wait briefly so VINS sees the padded topic available -->\n"

    viz_xml = ""
    if viz_spec:
        viz_xml = f"""
    <!-- Stereo fisheye tracking + VINS trajectory visualizer -->
    <node pkg="fishloop_vins" type="viz_fisheye_tracking.py" name="viz_fisheye_tracking"
          output="screen">
        <param name="left_topic"       type="string" value="{viz_spec['left_topic']}"/>
        <param name="right_topic"      type="string" value="{viz_spec['right_topic']}"/>
        <param name="left_compressed"  type="bool"   value="{str(bool(viz_spec['left_compressed'])).lower()}"/>
        <param name="right_compressed" type="bool"   value="{str(bool(viz_spec['right_compressed'])).lower()}"/>
        <param name="display"          type="bool"   value="{str(bool(viz_spec.get('display', True))).lower()}"/>
        <param name="show_width"       type="int"    value="{int(viz_spec.get('show_width', 1600))}"/>
        <param name="traj_height"      type="int"    value="{int(viz_spec.get('traj_height', 360))}"/>
        <param name="header_height"    type="int"    value="{int(viz_spec.get('header_height', 44))}"/>
        <param name="max_corners"      type="int"    value="{int(viz_spec.get('max_corners', 200))}"/>
        <param name="min_distance"     type="int"    value="{int(viz_spec.get('min_distance', 25))}"/>
        <param name="trail_length"     type="int"    value="{int(viz_spec.get('trail_length', 12))}"/>
        <param name="output_topic"     type="string" value="{viz_spec.get('output_topic', '/vins/fisheye_track')}"/>
        <param name="path_topic"       type="string" value="{viz_spec.get('path_topic', '/vins_estimator/path')}"/>
        <param name="odom_topic"       type="string" value="{viz_spec.get('odom_topic', '/vins_estimator/odometry')}"/>
        <param name="mask_path"        type="string" value="{_pkg_rel(viz_spec.get('mask_path', ''))}"/>
    </node>
"""

    body = f"""<launch>
    <!--
        Auto-generated by kalibr_to_vins.py.
        Run:
            roslaunch fishloop_vins {launch_name}.launch
            rosbag play YOUR.bag (use the clock flag)

        NOTE on the pad_fisheye_node.py path: roslaunch finds it via
            rosrun fishloop_vins pad_fisheye_node.py
        which requires CMakeLists.txt to install scripts/, OR the script
        being on PATH. We use rosrun-style lookup; if not found, copy or
        symlink scripts/pad_fisheye_node.py into the package install dir,
        or just run it directly:
            python3 {scripts_rel} _input:=... _output:=...
    -->
    <arg name="config_file" default="$(find fishloop_vins)/../{rel}" />
    <arg name="viz"         default="true" />
{padder_xml}{viz_xml}
    <node pkg="fishloop_vins" type="fishloop_vins_node_fisheye" name="vins_estimator" output="screen">
        <param name="config_file" type="string" value="$(arg config_file)"/>
        <param name="fisheye_external_flatten" type="bool" value="false"/>
    </node>

    <include file="$(find fishloop_vins)/launch/vins_rviz.launch" if="$(arg viz)" />
</launch>
"""
    target = launch_dir / f"{launch_name}.launch"
    target.write_text(body)
    return target


