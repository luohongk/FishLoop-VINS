def emit_main_config(
    out_path: Path,
    cam_pair: Tuple[int, int],
    cam_files: Dict[int, str],
    Tic: Dict[int, np.ndarray],
    resolution: Tuple[int, int],
    imu: dict,
    topic_map: Dict[int, str],
    imu_topic: str,
    compressed: bool,
    use_gpu: int,
    imu_noise_scale: float,
    output_path: str,
    timeshift_cam_imu: float,
    estimate_td: int,
    is_fisheye: int = 1,
    fisheye_fov: float = 200.0,
    enable_sides: int = 0,
    show_track: int = -1,
    pad_top: int = 0,
    pad_bottom: int = 0,
    pad_left: int = 0,
    pad_right: int = 0,
    padded_topic_suffix: str = "/image_padded",
    flatten_width: int = 600,
    flatten_height: int = 200,
    show_width: int = 1080,
) -> Path:
    a, b = cam_pair
    w, h = resolution
    body_T_cam0 = Tic[a]
    body_T_cam1 = Tic[b]

    # Padded image dimensions (advertised to VINS; raw fisheye_fov sub-image
    # sampler then sees a "square-ish" canvas matching its symmetry assumption).
    w_pad = int(w) + pad_left + pad_right
    h_pad = int(h) + pad_top + pad_bottom
    padding_active = (pad_top + pad_bottom + pad_left + pad_right) > 0

    raw0, raw1 = topic_map[a], topic_map[b]
    # Strip "/compressed" if user passed compressed topics directly
    if raw0.endswith("/compressed"):
        raw0 = raw0[: -len("/compressed")]
    if raw1.endswith("/compressed"):
        raw1 = raw1[: -len("/compressed")]
    comp0 = raw0 + "/compressed"
    comp1 = raw1 + "/compressed"

    if padding_active:
        # Padder consumes raw or compressed input, publishes to a new raw topic
        # that ends in `padded_topic_suffix`. VINS subscribes to that.
        # Strip the trailing /image_raw (or whatever) suffix and replace.
        def _padded(t: str) -> str:
            base = t.rsplit("/", 1)[0] if "/" in t else t
            return base + padded_topic_suffix
        raw0_in_for_vins = _padded(raw0)
        raw1_in_for_vins = _padded(raw1)
        comp0_in_for_vins = raw0_in_for_vins + "/compressed"
        comp1_in_for_vins = raw1_in_for_vins + "/compressed"
        # When padder is active, padded output is RAW, so force compressed-mode off
        compressed_for_vins = False
    else:
        raw0_in_for_vins = raw0
        raw1_in_for_vins = raw1
        comp0_in_for_vins = comp0
        comp1_in_for_vins = comp1
        compressed_for_vins = compressed

    acc_n = imu["accelerometer_noise_density"] * imu_noise_scale
    gyr_n = imu["gyroscope_noise_density"] * imu_noise_scale
    acc_w = imu["accelerometer_random_walk"] * imu_noise_scale
    gyr_w = imu["gyroscope_random_walk"] * imu_noise_scale
    update_rate = int(imu.get("update_rate", 200))

    # Auto-coordinate show_track with enable_sides:
    # drawTrackFisheye() in feature_tracker_fisheye.hpp:319 unconditionally
    # divides by imUpSide.size().width, which is 0 when sides are disabled,
    # causing a cv::resize assertion failure. So when sides are off we must
    # also force show_track=0. The user can override via --show-track.
    if show_track < 0:
        show_track = 1 if enable_sides else 0
    elif show_track == 1 and not enable_sides:
        print("[warn] show_track=1 without enable_sides=1 will crash "
              "drawTrackFisheye(). Forcing show_track=0.")
        show_track = 0

    cfg = f"""%YAML:1.0

#==========================================================
# Auto-generated by kalibr_to_vins.py — DO NOT EDIT BY HAND.
# Re-run the script to refresh.
#
# Camera pair selected: cam{a} + cam{b}
# IMU topic           : {imu_topic}
# Configured inputs   : {raw0} / {raw1}
# VINS subscribes to  : {raw0_in_for_vins} / {raw1_in_for_vins}
# Compressed input    : {bool(compressed_for_vins)}
# Padding             : top={pad_top} bottom={pad_bottom} left={pad_left} right={pad_right}
#                       (pad_fisheye_node.py rebuilds the symmetric fisheye)
# is_fisheye          : {int(is_fisheye)}  (1 = dual-fisheye spherical mode;
#                       this fork only implements the is_fisheye:1 path —
#                       the is_fisheye:0 branch in estimator.cpp is empty
#                       and segfaults at runtime.)
#==========================================================

#common parameters
imu: 1
num_of_cam: 2

is_fisheye: {int(is_fisheye)}

imu_topic: "{imu_topic}"

# Raw image topics (used when is_compressed_images:0)
image0_topic: "{raw0_in_for_vins}"
image1_topic: "{raw1_in_for_vins}"

# Compressed image topics (used when is_compressed_images:1)
is_compressed_images: {1 if compressed_for_vins else 0}
compressed_image0_topic: "{comp0_in_for_vins}"
compressed_image1_topic: "{comp1_in_for_vins}"

output_path: "{output_path}"

cam0_calib: "{cam_files[a]}"
cam1_calib: "{cam_files[b]}"

# image_width/height here are the FLATTENED virtual-pinhole sub-image
# dimensions (used as WIDTH inside FisheyeUndist), NOT the input fisheye
# resolution. Recommended 300-600 for VIO. The actual padded input size
# ({w_pad} x {h_pad}) is declared inside cam{a}_*.yaml / cam{b}_*.yaml.
image_width: {int(flatten_width)}
image_height: {int(flatten_height)}
show_width: {int(show_width)}      # SHOW_WIDTH for the show_track visualization

# Extrinsic parameter between IMU and Camera.
estimate_extrinsic: 0   # 0  trust the matrices below; 1  refine online.

body_T_cam0: !!opencv-matrix
   rows: 4
   cols: 4
   dt: d
   data: [
{fmt_matrix(body_T_cam0)} ]

body_T_cam1: !!opencv-matrix
   rows: 4
   cols: 4
   dt: d
   data: [
{fmt_matrix(body_T_cam1)} ]

#Multiple thread support
multiple_thread: 1
#GPU acceleration
use_gpu: {int(use_gpu)}
use_vxworks: 0

# Dual-fisheye sub-image flags. Each fisheye camera is unwarped into
# 5 virtual pinhole sub-images (top + 4 sides). For forward-facing stereo
# the "top" sub-image (cam optical axis) is the most useful one.
fisheye_fov: {float(fisheye_fov)}
enable_up_top: 1
enable_down_top: 1
enable_up_side: {int(enable_sides)}
enable_down_side: {int(enable_sides)}
enable_rear_side: 0
thres_outlier: 5.0
tri_max_err: 3.0
pub_flatten: 0
pub_flatten_freq: 10
flatten_color: 0
enable_downsample: 0

enable_depth: 0
rgb_depth_cloud: -1
depth_estimate_baseline: 0.05
depth_config: "depth_cpu.yaml"
top_cnt: 150
side_cnt: 100

#feature tracker parameters
max_cnt: 150
max_solve_cnt: 150
min_dist: 30
freq: 10
F_threshold: 1.0
show_track: {int(show_track)}
flow_back: 1
enable_perf_output: 0
use_orb: 0

warn_imu_freq: 0
warn_imu_duration: 0
imu_freq: {update_rate}
image_freq: 30

#optimization parameters
max_solver_time: 0.04
max_num_iterations: 8
keyframe_parallax: 10.0

#imu parameters (kalibr-derived, scaled by --imu-noise-scale = {imu_noise_scale})
acc_n: {acc_n:.8g}
gyr_n: {gyr_n:.8g}
acc_w: {acc_w:.8g}
gyr_w: {gyr_w:.8g}
g_norm: 9.81

#unsynchronization parameters
estimate_td: {int(estimate_td)}
td: {timeshift_cam_imu:.16e}      # kalibr "timeshift_cam_imu"

#loop closure parameters
load_previous_pose_graph: 0
pose_graph_save_path: "{output_path}/pose_graph/"
save_image: 0

#rectify
publish_rectify: 0
cam0_rectify: !!opencv-matrix
   rows: 3
   cols: 3
   dt: d
   data: [ 1, 0, 0,
           0, 1, 0,
           0, 0, 1 ]
cam1_rectify: !!opencv-matrix
   rows: 3
   cols: 3
   dt: d
   data: [ 1, 0, 0,
           0, 1, 0,
           0, 0, 1 ]
"""
    target = out_path / "stereo_imu_config.yaml"
    target.write_text(cfg)
    return target


