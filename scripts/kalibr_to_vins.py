def parse_topic_map(s: str, ncam: int) -> Dict[int, str]:
    if not s:
        return {i: f"/cam{i}/image_raw" for i in range(ncam)}
    out: Dict[int, str] = {}
    for piece in s.split(","):
        piece = piece.strip()
        if not piece:
            continue
        idx, topic = piece.split(":", 1)
        out[int(idx)] = topic.strip()
    for i in range(ncam):
        out.setdefault(i, f"/cam{i}/image_raw")
    return out


def parse_pair(s: str) -> Tuple[int, int]:
    a, b = (int(x) for x in s.split(","))
    return a, b


def main(argv=None):
    here = Path(__file__).resolve().parent
    repo_root = here.parent  # .../VINS-Fisheye

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--kalibr-dir", type=Path,
                   default=repo_root / "my_kalibr_result",
                   help="Directory containing kalibr *.yaml outputs.")
    p.add_argument("--out-dir", type=Path,
                   default=repo_root / "config" / "my_kalibr_fisheye",
                   help="Destination directory for VINS yaml files.")
    p.add_argument("--cam-pair", default="0,1",
                   help="Indices of the stereo pair, e.g. 0,1 or 2,3.")
    p.add_argument("--topic-map", default="0:/fisheye/left/image_raw,"
                                          "1:/fisheye/right/image_raw,"
                                          "2:/fisheye/bleft/image_raw,"
                                          "3:/fisheye/bright/image_raw",
                   help="Comma-separated cam_idx:topic pairs (raw image topic).")
    p.add_argument("--imu-topic", default="/imu_data_raw",
                   help="ROS topic for sensor_msgs/Imu in the bag.")
    p.add_argument("--compressed", action="store_true", default=True,
                   help="Set is_compressed_images:1 in the main config (default ON).")
    p.add_argument("--no-compressed", dest="compressed", action="store_false",
                   help="Disable compressed image input.")
    p.add_argument("--use-gpu", type=int, default=0, choices=[0, 1],
                   help="use_gpu flag (set 1 only if you built with CUDA support).")
    p.add_argument("--imu-noise-scale", type=float, default=10.0,
                   help="Multiplier applied to kalibr IMU noise/random-walk (default 10x).")
    p.add_argument("--output-path", default="/home/lhk/output",
                   help="VINS output_path field.")
    p.add_argument("--estimate-td", type=int, default=0, choices=[0, 1],
                   help="Estimate camera/IMU time offset online. Default 0 uses "
                        "Kalibr's timeshift_cam_imu as a fixed value.")
    p.add_argument("--is-fisheye", type=int, default=1, choices=[0, 1],
                   help="is_fisheye flag. NOTE: this fork only implements the "
                        "is_fisheye:1 dual-fisheye path; is_fisheye:0 segfaults.")
    p.add_argument("--fisheye-fov", type=float, default=200.0,
                   help="Total fisheye FOV in degrees (used for sub-image sampling).")
    p.add_argument("--enable-sides", type=int, default=0, choices=[0, 1],
                   help="Enable the 4 side sub-images per camera (default off; "
                        "for forward-facing stereo, side sub-images often have "
                        "no useful content).")
    p.add_argument("--show-track", type=int, default=-1, choices=[-1, 0, 1],
                   help="show_track flag. -1 (default) = auto: 1 if sides "
                        "enabled, 0 otherwise. drawTrackFisheye() crashes when "
                        "sides are disabled, so this auto-mode prevents that.")
    p.add_argument("--pad-top",    type=int, default=0,
                   help="Pad N pixels of black on top of each image at runtime.")
    p.add_argument("--pad-bottom", type=int, default=0,
                   help="Pad N pixels of black on bottom of each image at runtime.")
    p.add_argument("--pad-left",   type=int, default=0,
                   help="Pad N pixels of black on left of each image at runtime.")
    p.add_argument("--pad-right",  type=int, default=0,
                   help="Pad N pixels of black on right of each image at runtime.")
    p.add_argument("--padded-suffix", default="/image_padded",
                   help="Topic suffix appended to the basename for padded output "
                        "(e.g. /fisheye/left -> /fisheye/left/image_padded).")
    p.add_argument("--flatten-width",  type=int, default=600,
                   help="Width of the virtual-pinhole sub-images produced by "
                        "FisheyeUndist (main yaml's image_width). Recommended "
                        "300-600 for VIO. Lower = faster.")
    p.add_argument("--flatten-height", type=int, default=200,
                   help="Height of the side virtual-pinhole strip "
                        "(main yaml's image_height).")
    p.add_argument("--show-width",     type=int, default=1080,
                   help="show_width: width of the show_track visualization "
                        "window. Must be > 0 or drawTrackFisheye crashes.")
    p.add_argument("--external-viz", type=int, default=1, choices=[0, 1],
                   help="Add a viz_fisheye_tracking.py node to the launch file "
                        "(simple side-by-side fisheye tracking window, "
                        "independent of VINS's internal show_track). When 1, "
                        "VINS's own show_track is also auto-disabled.")
    p.add_argument("--fisheye-mask", default="",
                   help="Path to a fisheye PNG mask (white = valid, black = "
                        "ignore). The viz node will only detect features "
                        "inside the mask. Auto-padded if its aspect ratio "
                        "differs from the runtime image (e.g. mask drawn for "
                        "the un-padded sensor).")
    p.add_argument("--launch", default=None,
                   help="If set, write vins_estimator/launch/<NAME>.launch alongside.")
    p.add_argument("--launch-dir", type=Path,
                   default=repo_root / "vins_estimator" / "launch",
                   help="Directory for the optional launch file.")
    args = p.parse_args(argv)

    # ------- locate kalibr files -------
    kalibr_dir = args.kalibr_dir.resolve()
    if not kalibr_dir.exists():
        sys.exit(f"[err] kalibr dir does not exist: {kalibr_dir}")
    imucam_path   = find_one("*camchain-imucam*.yaml", kalibr_dir)
    camchain_path = find_one("*camchain.yaml",         kalibr_dir)
    imu_path      = find_one("*imu-imu*.yaml",         kalibr_dir)

    print(f"[info] imucam   : {imucam_path}")
    print(f"[info] camchain : {camchain_path}")
    print(f"[info] imu      : {imu_path}")

    imucam   = load_yaml(imucam_path)
    camchain = load_yaml(camchain_path)
    imu_yaml = load_yaml(imu_path)

    ncam = num_cameras(camchain)
    if ncam == 0:
        sys.exit("[err] no cameras found in camchain")
    print(f"[info] detected {ncam} cameras (cam0..cam{ncam-1})")

    # ------- compute extrinsics -------
    T_cam0_imu = np.array(imucam["cam0"]["T_cam_imu"])
    T_imu_cam0 = invert_se3(T_cam0_imu)
    Tic = {i: T_imu_cam(camchain, T_imu_cam0, i) for i in range(ncam)}
    timeshift = float(imucam["cam0"].get("timeshift_cam_imu", 0.0))

    # ------- write output -------
    args.out_dir.mkdir(parents=True, exist_ok=True)
    cam_files: Dict[int, str] = {}
    resolution = tuple(camchain["cam0"]["resolution"])
    for i in range(ncam):
        cam_files[i] = emit_camera_yaml(
            args.out_dir, i, camchain[f"cam{i}"],
            pad_top=args.pad_top, pad_bottom=args.pad_bottom,
            pad_left=args.pad_left, pad_right=args.pad_right,
        )
        print(f"[ok ] wrote {args.out_dir/cam_files[i]}")

    cam_pair = parse_pair(args.cam_pair)
    if cam_pair[0] not in Tic or cam_pair[1] not in Tic:
        sys.exit(f"[err] cam-pair {cam_pair} out of range (have 0..{ncam-1})")
    topic_map = parse_topic_map(args.topic_map, ncam)

    # When the external viz node is on, force VINS's broken show_track off.
    show_track_arg = args.show_track
    if args.external_viz and show_track_arg != 0:
        print("[info] --external-viz=1 -> forcing VINS show_track:0 "
              "(use the standalone viz_fisheye_tracking window instead)")
        show_track_arg = 0

    imu0 = imu_yaml["imu0"]
    main_yaml = emit_main_config(
        out_path=args.out_dir,
        cam_pair=cam_pair,
        cam_files=cam_files,
        Tic=Tic,
        resolution=resolution,
        imu=imu0,
        topic_map=topic_map,
        imu_topic=args.imu_topic,
        compressed=args.compressed,
        use_gpu=args.use_gpu,
        imu_noise_scale=args.imu_noise_scale,
        output_path=args.output_path,
        timeshift_cam_imu=timeshift,
        estimate_td=args.estimate_td,
        is_fisheye=args.is_fisheye,
        fisheye_fov=args.fisheye_fov,
        enable_sides=args.enable_sides,
        show_track=show_track_arg,
        pad_top=args.pad_top, pad_bottom=args.pad_bottom,
        pad_left=args.pad_left, pad_right=args.pad_right,
        padded_topic_suffix=args.padded_suffix,
        flatten_width=args.flatten_width,
        flatten_height=args.flatten_height,
        show_width=args.show_width,
    )
    print(f"[ok ] wrote {main_yaml}")

    # ------- build padder specs (only if any padding requested) -------
    padder_specs = []
    pad_total = args.pad_top + args.pad_bottom + args.pad_left + args.pad_right
    if pad_total > 0:
        for cam_idx in cam_pair:
            src = topic_map[cam_idx]
            if src.endswith("/compressed"):
                src = src[: -len("/compressed")]
            base = src.rsplit("/", 1)[0] if "/" in src else src
            padded_out = base + args.padded_suffix
            padder_specs.append({
                "input": (src + "/compressed") if args.compressed else src,
                "output": padded_out,
                "input_compressed": args.compressed,
                "pad_top": args.pad_top,
                "pad_bottom": args.pad_bottom,
                "pad_left": args.pad_left,
                "pad_right": args.pad_right,
            })

    # ------- build viz spec (so the launch file knows what topics to viz) -------
    viz_spec = None
    if args.external_viz:
        # Subscribe to whichever topic actually carries the images we want VINS
        # to consume. With padding active, that's the padded raw topic; without
        # padding, the original raw or compressed topic the user supplied.
        a, b = cam_pair
        raw_a = topic_map[a]
        raw_b = topic_map[b]
        if raw_a.endswith("/compressed"):
            raw_a = raw_a[: -len("/compressed")]
        if raw_b.endswith("/compressed"):
            raw_b = raw_b[: -len("/compressed")]
        if pad_total > 0:
            base_a = raw_a.rsplit("/", 1)[0] if "/" in raw_a else raw_a
            base_b = raw_b.rsplit("/", 1)[0] if "/" in raw_b else raw_b
            viz_left  = base_a + args.padded_suffix
            viz_right = base_b + args.padded_suffix
            viz_left_comp = False
            viz_right_comp = False
        else:
            viz_left  = raw_a + ("/compressed" if args.compressed else "")
            viz_right = raw_b + ("/compressed" if args.compressed else "")
            viz_left_comp = bool(args.compressed)
            viz_right_comp = bool(args.compressed)
        viz_spec = {
            "left_topic":  viz_left,
            "right_topic": viz_right,
            "left_compressed":  viz_left_comp,
            "right_compressed": viz_right_comp,
            "display": True,
            "show_width": 1600,
            "max_corners": 200,
            "min_distance": 25,
            "trail_length": 12,
            "traj_height": 360,
            "header_height": 44,
            "path_topic": "/vins_estimator/path",
            "odom_topic": "/vins_estimator/odometry",
            "output_topic": "/vins/fisheye_track",
            "mask_path": str(Path(args.fisheye_mask).resolve()) if args.fisheye_mask else "",
        }

    # ------- optional launch file -------
    if args.launch:
        args.launch_dir.mkdir(parents=True, exist_ok=True)
        launch_path = emit_launch(args.launch_dir, args.launch, main_yaml,
                                  padder_specs=padder_specs,
                                  viz_spec=viz_spec)
        print(f"[ok ] wrote {launch_path}")

    # ------- summary -------
    print()
    print("Summary:")
    print(f"  cam pair   : cam{cam_pair[0]} + cam{cam_pair[1]}")
    print(f"  baseline   : {np.linalg.norm(Tic[cam_pair[0]][:3,3] - Tic[cam_pair[1]][:3,3]):.4f} m")
    print(f"  imu rate   : {imu0.get('update_rate','?')} Hz")
    print(f"  td (kalibr): {timeshift:+.6f} s  (image_t + td = imu_t)")
    print(f"  imu noise  : x{args.imu_noise_scale}")
    if pad_total > 0:
        w0, h0 = resolution
        print(f"  pad        : t={args.pad_top} b={args.pad_bottom} "
              f"l={args.pad_left} r={args.pad_right}  "
              f"->  {w0+args.pad_left+args.pad_right} x {h0+args.pad_top+args.pad_bottom}")
    print()
    print("Run:")
    print(f"  roslaunch fishloop_vins {(args.launch or 'my_kalibr_fisheye')}.launch")
    print(f"  rosbag play <your.bag> --clock")


if __name__ == "__main__":
    main()
