def emit_camera_yaml(out_path: Path, cam_idx: int, cam: dict,
                     pad_top: int = 0, pad_bottom: int = 0,
                     pad_left: int = 0, pad_right: int = 0) -> str:
    """Write a VINS camera-intrinsics yaml. Returns the file basename.

    Padding shifts the principal point (u0, v0) accordingly and grows the
    declared image size, so the kalibr-fitted intrinsics remain valid for
    the padded image (the lens-sensor relationship doesn't change; we just
    place the active region inside a larger canvas)."""
    model_kalibr = f"{cam.get('camera_model','omni')}-{cam.get('distortion_model','radtan')}"
    intr = cam["intrinsics"]
    dist = cam["distortion_coeffs"]
    w, h = cam["resolution"]
    name = f"cam{cam_idx}"

    # Padded geometry
    w_pad = int(w) + pad_left + pad_right
    h_pad = int(h) + pad_top + pad_bottom

    if model_kalibr == "eucm-none":
        alpha, beta, fx, fy, cx, cy = intr
        cx_pad = cx + pad_left
        cy_pad = cy + pad_top
        body = f"""%YAML:1.0
---
# Generated by kalibr_to_vins.py from camchain.yaml ({name})
# Kalibr EUCM parameters are preserved exactly.
# Pad applied (top,bottom,left,right) = ({pad_top},{pad_bottom},{pad_left},{pad_right})
model_type: EUCM
camera_name: {name}
image_width: {w_pad}
image_height: {h_pad}
projection_parameters:
   alpha: {alpha:.16e}
   beta: {beta:.16e}
   fx: {fx:.16e}
   fy: {fy:.16e}
   cx: {cx_pad:.16e}
   cy: {cy_pad:.16e}
"""
    elif model_kalibr == "omni-radtan":
        xi, fx, fy, cx, cy = intr
        k1, k2, p1, p2 = dist
        cx_pad = cx + pad_left
        cy_pad = cy + pad_top
        body = f"""%YAML:1.0
---
# Generated by kalibr_to_vins.py from camchain.yaml ({name})
# Kalibr "omni-radtan" -> VINS "MEI"
# Pad applied (top,bottom,left,right) = ({pad_top},{pad_bottom},{pad_left},{pad_right})
model_type: MEI
camera_name: {name}
image_width: {w_pad}
image_height: {h_pad}
mirror_parameters:
   xi: {xi:.16e}
distortion_parameters:
   k1: {k1:.16e}
   k2: {k2:.16e}
   p1: {p1:.16e}
   p2: {p2:.16e}
projection_parameters:
   gamma1: {fx:.16e}
   gamma2: {fy:.16e}
   u0: {cx_pad:.16e}
   v0: {cy_pad:.16e}
"""
    elif model_kalibr == "pinhole-radtan":
        fx, fy, cx, cy = intr
        k1, k2, p1, p2 = dist
        cx_pad = cx + pad_left
        cy_pad = cy + pad_top
        body = f"""%YAML:1.0
---
# Generated by kalibr_to_vins.py from camchain.yaml ({name})
# Kalibr "pinhole-radtan" -> VINS "PINHOLE"
# Pad applied (top,bottom,left,right) = ({pad_top},{pad_bottom},{pad_left},{pad_right})
model_type: PINHOLE
camera_name: {name}
image_width: {w_pad}
image_height: {h_pad}
distortion_parameters:
   k1: {k1:.16e}
   k2: {k2:.16e}
   p1: {p1:.16e}
   p2: {p2:.16e}
projection_parameters:
   fx: {fx:.16e}
   fy: {fy:.16e}
   cx: {cx_pad:.16e}
   cy: {cy_pad:.16e}
"""
    elif model_kalibr == "pinhole-equi":
        fx, fy, cx, cy = intr
        k1, k2, k3, k4 = dist
        cx_pad = cx + pad_left
        cy_pad = cy + pad_top
        body = f"""%YAML:1.0
---
# Generated by kalibr_to_vins.py from camchain.yaml ({name})
# Kalibr "pinhole-equi" -> VINS "KANNALA_BRANDT"
# Pad applied (top,bottom,left,right) = ({pad_top},{pad_bottom},{pad_left},{pad_right})
model_type: KANNALA_BRANDT
camera_name: {name}
image_width: {w_pad}
image_height: {h_pad}
projection_parameters:
   k2: {k1:.16e}
   k3: {k2:.16e}
   k4: {k3:.16e}
   k5: {k4:.16e}
   mu: {fx:.16e}
   mv: {fy:.16e}
   u0: {cx_pad:.16e}
   v0: {cy_pad:.16e}
"""
    else:
        raise ValueError(
            f"Unsupported Kalibr model {model_kalibr!r} for {name}. "
            "Supported: eucm-none, omni-radtan, pinhole-radtan, pinhole-equi."
        )

    fname = f"{name}_{ {'eucm-none':'eucm','omni-radtan':'mei','pinhole-radtan':'pinhole','pinhole-equi':'kb'}[model_kalibr] }.yaml"
    (out_path / fname).write_text(body)
    return fname


